#!/usr/bin/env bash
# tmux-theme.sh — write ~/.config/tmux/theme.conf from a kshell palette.
#
#   tmux-theme.sh <name> <accent> <highlight> <foreground> <dim> <mid> <background>
#
# Colours are the ones in kshell's [theme] section: "#RRGGBB" or "#RRGGBBAA".
# tmux has no alpha, so the alpha byte is dropped and translucent surfaces are
# approximated by blending the background toward the foreground.
#
# A live tmux server is reloaded in place, so switching theme in kshell
# repaints the panes, borders and status bar without restarting a session.

set -euo pipefail

NAME=${1:-theme}
ACCENT=${2:-#888888}
HIGHLIGHT=${3:-#ffffff}
FOREGROUND=${4:-#cccccc}
DIM=${5:-#666666}
MID=${6:-#999999}
BACKGROUND=${7:-#111111}

CONF="${TMUX_THEME_CONF:-$HOME/.config/tmux/theme.conf}"

# Accepts "#RRGGBB", "#RRGGBBAA" (alpha last) and "0xAARRGGBB" (alpha first) —
# the two orders kshell's config uses — and returns bare "rrggbb".
strip() {
  local raw=$1 c
  if [[ $raw == 0x* || $raw == 0X* ]]; then
    c=${raw:2}
    c=${c:2:6}                       # 0xAARRGGBB -> RRGGBB
  else
    c=${raw#\#}
    [ ${#c} -eq 8 ] && c=${c:0:6}    # #RRGGBBAA -> RRGGBB
  fi
  case ${#c} in
    3) c="${c:0:1}${c:0:1}${c:1:1}${c:1:1}${c:2:1}${c:2:1}" ;;
    6) : ;;
    *) c="888888" ;;                 # anything unparseable stays legible
  esac
  printf '%s' "$c"
}

# blend <from> <to> <percent-toward-to>  ->  "rrggbb"
blend() {
  local a b p i ra rb out=""
  a=$(strip "$1"); b=$(strip "$2"); p=${3:-10}
  for i in 0 2 4; do
    ra=$((16#${a:i:2})); rb=$((16#${b:i:2}))
    out+=$(printf '%02x' $(( (ra * (100 - p) + rb * p) / 100 )))
  done
  printf '%s' "$out"
}

BG=$(strip "$BACKGROUND")
FG=$(strip "$FOREGROUND")
AC=$(strip "$ACCENT")
HI=$(strip "$HIGHLIGHT")
DM=$(strip "$DIM")
STATUS_BG=$(blend "$BACKGROUND" "$FOREGROUND" 8)
SEL_BG=$(blend "$BACKGROUND" "$MID" 22)

mkdir -p "$(dirname "$CONF")"

cat > "$CONF" <<EOF
# Generated by ~/dotfiles/scripts/tmux-theme.sh — do not edit by hand.
# Source: kshell theme "$NAME"
#
# Every colour below comes from kshell's [theme] palette, so kitty, nvim, ked
# and tmux agree. Re-run the theme switch (or 'kshell theme <name>') to rewrite.

# ── status bar ─────────────────────────────────────────────────────────────
# Deliberately bg=default: the bar paints no background at all, so kitty's
# opacity and blur show through it and the wallpaper is the bar. Colour lives in
# the foreground only — accent for the session and the current window, dim for
# the rest — which keeps it readable without putting a slab over the desktop.
set -g status-style "bg=default,fg=#${FG}"
set -g status-left-style "bg=default,fg=#${AC},bold"
set -g status-right-style "bg=default,fg=#${DM}"
set -g window-status-style "bg=default,fg=#${DM}"
set -g window-status-current-style "bg=default,fg=#${AC},bold"
set -g window-status-activity-style "bg=default,fg=#${HI},bold"
set -g status-left "#[fg=#${AC},bold] #S "
set -g status-right "#[fg=#${DM}]#{?window_zoomed_flag,[Z] ,}#{b:pane_current_path} "
set -g window-status-format " #[fg=#${DM}]#I:#{b:pane_current_path} "
set -g window-status-current-format " #[fg=#${AC},bold]#I:#{b:pane_current_path} "

# ── panes ──────────────────────────────────────────────────────────────────
set -g pane-border-style "fg=#${DM}"
set -g pane-active-border-style "fg=#${AC}"
set -g pane-border-status off

# ── messages, menus, modes ─────────────────────────────────────────────────
set -g message-style "bg=#${AC},fg=#${BG}"
set -g message-command-style "bg=#${AC},fg=#${BG}"
set -g mode-style "bg=#${SEL_BG},fg=#${FG}"
set -g display-panes-colour "#${DM}"
set -g display-panes-active-colour "#${AC}"
set -g clock-mode-colour "#${HI}"
set -g copy-mode-match-style "bg=#${SEL_BG},fg=#${FG},bold"
set -g copy-mode-current-match-style "bg=#${AC},fg=#${BG},bold"
set -g popup-style "bg=#${STATUS_BG},fg=#${FG}"
set -g popup-border-style "fg=#${AC}"
EOF

# Reload a running server in place; no server is not an error.
if command -v tmux >/dev/null 2>&1 && tmux list-sessions >/dev/null 2>&1; then
  tmux source-file "$CONF" 2>/dev/null || true
  tmux refresh-client -S 2>/dev/null || true
  echo "tmux: theme.conf written from \"$NAME\" and reloaded"
else
  echo "tmux: theme.conf written from \"$NAME\" (no server running)"
fi
